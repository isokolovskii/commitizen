package cmd

import (
	"context"
	"fmt"
	"io"
	"os"

	"github.com/urfave/cli/v3"

	"github.com/isokolovskii/commitizen/internal/config"
)

func exampleCommand() *cli.Command {
	return &cli.Command{
		Name:  "example",
		Usage: "print an example message generated by the default adapter",
		Action: func(_ context.Context, _ *cli.Command) error {
			err := runExample(os.Stdout)
			if err != nil {
				return fmt.Errorf("running example command: %w", err)
			}

			return nil
		},
	}
}

// runExample prints the example message of the default adapter to out.
func runExample(out io.Writer) error {
	registry, err := builtinRegistry(config.Default())
	if err != nil {
		return fmt.Errorf(errBuildRegistry, err)
	}

	adapter, err := registry.Get(config.DefaultAdapter)
	if err != nil {
		return fmt.Errorf("resolving default adapter: %w", err)
	}

	example, err := adapter.Example()
	if err != nil {
		return fmt.Errorf("generating example: %w", err)
	}

	_, err = fmt.Fprint(out, example)
	if err != nil {
		return fmt.Errorf("printing example: %w", err)
	}

	return nil
}
